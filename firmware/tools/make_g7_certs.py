#!/usr/bin/env python3
"""
Builds src/g7_certs.h -- the app certificates + signing key a 4-digit G7 wants
on its first pairing (libkeks "Missing QR code") -- from xDrip+'s keks_p1..p3.

xDrip+ gets these from the one-time "Auto configure" QR code in its G7 setup
guide and keeps them as hex strings in its preferences. Feed this script either
an xDrip+ settings export (Settings -> Load/Save settings -> Save, the file
com.eveningoutpost.dexdrip_preferences.xml), a text file with three lines
`keks_p1=<hex>`, `keks_p2=<hex>`, `keks_p3=<hex>`, or the decoded text of the
setup QR code itself (starts with "xdp2:"):

    python make_g7_certs.py <file>

keks_p1 / keks_p2 are sent to the sensor as-is (certificate A / B); keks_p3 is
a PKCS#8 P-256 private key, of which only the raw 32-byte scalar goes into the
header. g7_auth.c picks the header up automatically on the next build. Keep
the generated file private -- it is a signing key.
"""

import base64
import gzip
import os
import re
import struct
import sys
import xml.etree.ElementTree as ET

from cryptography import x509
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.serialization import (Encoding, PublicFormat,
                                                          load_der_private_key)


def decode_xdp2(text):
    """xDrip+ QRcodeUtils.decodeString() for the binary "xdp2:" QR format:
    base64 (no padding) -> gzip -> u16 count, then per entry u16 key length,
    key, u16 value length, value (big-endian); "b__" keys hold raw bytes."""
    data = base64.b64decode(text + "=" * (-len(text) % 4))
    buf = gzip.decompress(data)
    (count,), off = struct.unpack_from(">H", buf), 2
    entries = {}
    for _ in range(count):
        (klen,) = struct.unpack_from(">H", buf, off); off += 2
        key = buf[off:off + klen].decode(); off += klen
        (vlen,) = struct.unpack_from(">H", buf, off); off += 2
        entries[key.removeprefix("b__")] = buf[off:off + vlen].hex(); off += vlen
    return entries


def read_parts(path):
    text = open(path, encoding="utf-8", errors="replace").read()
    parts = {}
    if text.strip().startswith("xdp2:"):
        parts = decode_xdp2(text.strip()[len("xdp2:"):])
    elif text.lstrip().startswith("<"):
        for el in ET.fromstring(text).iter("string"):
            if re.fullmatch(r"keks_p[123]", el.get("name", "")):
                parts[el.get("name")] = el.text or ""
    else:
        for m in re.finditer(r"(keks_p[123])\s*[=:]\s*([0-9A-Fa-f\s:]+)", text):
            parts[m.group(1)] = m.group(2)
    missing = [k for k in ("keks_p1", "keks_p2", "keks_p3") if not parts.get(k)]
    if missing:
        sys.exit(f"missing {', '.join(missing)} in {path}")
    # Same as xDrip+'s JoH.tolerantHexStringToByteArray: drop non-hex characters.
    return {k: bytes.fromhex(re.sub(r"[^0-9A-Fa-f]", "", v)) for k, v in parts.items()}


def c_array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 12]) for i in range(0, len(data), 12)]
    return f"static const uint8_t {name}[{len(data)}] = {{\n\t" + ",\n\t".join(rows) + ",\n};\n"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    parts = read_parts(sys.argv[1])

    key = load_der_private_key(parts["keks_p3"], password=None)
    if not isinstance(key, ec.EllipticCurvePrivateKey) or key.curve.name != "secp256r1":
        sys.exit("keks_p3 is not a P-256 private key")
    scalar = key.private_numbers().private_value.to_bytes(32, "big")

    for k in ("keks_p1", "keks_p2"):
        if len(parts[k]) <= 100:
            sys.exit(f"{k} is only {len(parts[k])} bytes -- libkeks requires > 100")

    # keks_p2 is the leaf certificate for keks_p3's key; keep its public key so
    # the firmware self-test can check the pair.
    pub = key.public_key().public_bytes(Encoding.X962, PublicFormat.UncompressedPoint)
    cert_pub = x509.load_der_x509_certificate(parts["keks_p2"]).public_key().public_bytes(
        Encoding.X962, PublicFormat.UncompressedPoint)
    if cert_pub != pub:
        sys.exit("keks_p2's public key does not match keks_p3")

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "g7_certs.h")
    with open(out, "w", newline="\n") as f:
        f.write("/* Generated by tools/make_g7_certs.py -- private, do not share. */\n")
        f.write("#ifndef G7_CERTS_H_\n#define G7_CERTS_H_\n\n#include <stdint.h>\n\n")
        f.write(c_array("g7_cert_a", parts["keks_p1"]))
        f.write(c_array("g7_cert_b", parts["keks_p2"]))
        f.write(c_array("g7_cert_key", scalar))
        f.write(c_array("g7_cert_pub", pub[1:]))
        f.write("\n#endif /* G7_CERTS_H_ */\n")
    print(f"wrote {os.path.normpath(out)}: cert A {len(parts['keks_p1'])} B, "
          f"cert B {len(parts['keks_p2'])} B, key OK")


if __name__ == "__main__":
    main()
